// A tiny built-in "stroke" font: each glyph is a list of line segments on a
// 4 (wide) x 6 (tall) unit grid. This avoids depending on an external .ttf
// file, at the cost of looking blocky. Good enough for a first-milestone
// browser; swap in `fontdue`/`ab_glyph` + a real font later for nicer text.

pub type Segment = (f32, f32, f32, f32);

pub const GLYPH_W: f32 = 4.0;
pub const GLYPH_H: f32 = 6.0;

fn seg(x0: f32, y0: f32, x1: f32, y1: f32) -> Segment {
    (x0, y0, x1, y1)
}

